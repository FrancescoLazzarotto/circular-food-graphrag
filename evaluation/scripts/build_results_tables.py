"""Emit the LaTeX tables of the results chapter from a campaign root.

Transcribing six generators times eight strategies times two levels by hand is
where a thesis acquires numbers that no run produced. This reads the scorer's
own JSON from each model directory and writes the tables, so the document and
the artifacts cannot disagree.

One row per strategy, one column per generator, in the campaign's execution
order. Strategies keep the thesis names: the runs call the flat-lookup preset
``text_plus_triples`` and the thesis calls it ``nodes_plus_triples``, and the
rename happens here rather than in the reader's head.

Usage::

    conda run -n graphllm python evaluation/scripts/build_results_tables.py \\
        --campaign-root /srv/projects/graphllm/experiments/exp_results_v3graph \\
        --out chapters/generated_results_tables.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

# Execution order of the campaign, with the label the thesis uses.
MODELS = [
    ("qwen3_30b_a3b_fp8", "Qwen3-30B"),
    ("qwen25_32b_awq", "Qwen2.5-32B"),
    ("qwen25_7b", "Qwen2.5-7B"),
    ("deepseek_r1_distill_32b_awq", "DeepSeek-32B"),
    ("qwen3_32b_awq", "Qwen3-32B"),
    ("gemma3_27b_awq", "Gemma-3-27B"),
]

# Graph strategies first, then the two controls, with a rule between them.
STRATEGIES = [
    ("hybrid", r"\ident{hybrid}"),
    ("default", r"\ident{default}"),
    ("subgraph_2hop", r"\ident{subgraph\_2hop}"),
    ("shortest_path", r"\ident{shortest\_path}"),
    ("neighbors_focus", r"\ident{neighbors\_focus}"),
    ("text_plus_triples", r"\ident{nodes\_plus\_triples}"),
    (None, None),
    ("text_only", r"\ident{text\_only}"),
    ("no_retrieval", r"\ident{no\_retrieval}"),
]


def load(root: Path) -> dict[str, dict]:
    """slug -> scorer report, for the models that produced one."""
    reports = {}
    for slug, _ in MODELS:
        path = root / slug / "gold_score.json"
        if path.exists():
            reports[slug] = json.loads(path.read_text(encoding="utf-8"))
    return reports


def value(report: dict, channel: str, strategy: str, block: str, field: str) -> float | None:
    """One field of one strategy's block in a scorer report; None when absent."""
    for entry in report[channel]["by_pipeline"]:
        if entry["keys"]["pipeline"] == strategy:
            return entry[block][field]
    return None


def table(reports: dict[str, dict], channel: str, block: str, field: str,
          caption: str, label: str) -> str:
    """One LaTeX table: a row per strategy, a column per generator present."""
    present = [(slug, name) for slug, name in MODELS if slug in reports]
    lines = [
        r"\begin{table}[t]", r"\centering", rf"\caption{{{caption}}}",
        rf"\label{{{label}}}", r"\small",
        r"\begin{tabular}{@{}l" + "r" * len(present) + r"@{}}", r"\toprule",
        r"\textbf{Strategy} & " + " & ".join(rf"\textbf{{{n}}}" for _, n in present) + r" \\",
        r"\midrule",
    ]
    for strategy, pretty in STRATEGIES:
        if strategy is None:
            lines.append(r"\midrule")
            continue
        cells = []
        for slug, _ in present:
            score = value(reports[slug], channel, strategy, block, field)
            cells.append("--" if score is None else f"{score:.3f}")
        lines.append(f"{pretty} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Parse arguments and write the LaTeX tables."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaign-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)

    reports = load(args.campaign_root)
    if not reports:
        parser.error(f"no gold_score.json under {args.campaign_root}")
    missing = [slug for slug, _ in MODELS if slug not in reports]
    if missing:
        print(f"WARNING: no score for {', '.join(missing)}; columns omitted")

    parts = [
        "% Generated by evaluation/scripts/build_results_tables.py. Do not edit by hand.\n",
        table(reports, "answer", "concept_micro", "f1",
              "Answer channel, concept-level micro F1. Every cell is 30 questions under one "
              "strategy and one generator, on the graph of \\Cref{tab:kg-reference} at the "
              "configuration of \\Cref{tab:agent-config}.",
              "tab:e10-concept"),
        table(reports, "answer", "grounding_micro", "f1",
              "Answer channel, grounding-level micro F1, over the 30 expected concepts that "
              "carry a canonical identifier. Read against \\Cref{tab:e10-concept}: the gap "
              "between the two is the interoperability cost of \\Cref{sec:onto-coverage}.",
              "tab:e10-grounding"),
        table(reports, "answer", "concept_micro", "recall",
              "Answer channel, concept-level micro recall. Precision is scored against the "
              "reference vocabulary only (\\Cref{sec:setup-noise}), so recall is the "
              "meaningful direction.",
              "tab:e10-recall"),
        table(reports, "retrieval", "concept_micro", "recall",
              "Retrieval channel, concept-level micro recall. Zero by construction for the two "
              "strategies that surface no entities, which is why the channel-agnostic measure "
              "of \\Cref{tab:e9-ctxrecall} exists.",
              "tab:e10-retrieval"),
    ]
    args.out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {args.out} with {len(reports)} generators")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
